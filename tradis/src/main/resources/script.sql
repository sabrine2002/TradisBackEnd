CREATE TABLE IF NOT EXISTS parameters (
                                          id_param BIGINT AUTO_INCREMENT PRIMARY KEY,
                                          cacc VARCHAR(50),
    cnom VARCHAR(50),
    label1 VARCHAR(255),
    label2 VARCHAR(255),
    label3 VARCHAR(255),
    label4 VARCHAR(255),
    label5 VARCHAR(255),
    label6 VARCHAR(255),
    label7 VARCHAR(255),
    label8 VARCHAR(255),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    CONSTRAINT unique_param_row UNIQUE (cnom, cacc)
    );

CREATE TABLE IF NOT EXISTS pdnom (
                                     id INT(50) AUTO_INCREMENT PRIMARY KEY,
    cnom VARCHAR(50),
    description TEXT NOT NULL
    );

CREATE TABLE IF NOT EXISTS users (
                                     id BIGINT AUTO_INCREMENT PRIMARY KEY,
                                     username VARCHAR(255) NOT NULL UNIQUE,
    password VARCHAR(255) NOT NULL,
    LastName VARCHAR(255),
    FirstName VARCHAR(255),
    created_by BIGINT,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_by BIGINT,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    CONSTRAINT unique_user_row UNIQUE (username, LastName, FirstName)
    );

CREATE TABLE IF NOT EXISTS clients (
                                       id_client BIGINT AUTO_INCREMENT PRIMARY KEY,
                                       Firstname VARCHAR(50) NOT NULL,
    Lastname VARCHAR(50),
    nationality VARCHAR(50), -- Kept as VARCHAR for cnom values
    resident BOOLEAN NOT NULL,
    accountType VARCHAR(50) NOT NULL, -- Kept as VARCHAR
    DocumentType VARCHAR(50) NOT NULL, -- Kept as VARCHAR
    accountcurrency VARCHAR(50) NOT NULL, -- Kept as VARCHAR
    accountINT VARCHAR(20) NOT NULL,
    agency VARCHAR(50), -- Kept as VARCHAR
    accountCreationDate DATE,
    accountColsureDate DATE,
    created_by BIGINT,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_by BIGINT,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    CONSTRAINT unique_client_row UNIQUE (Firstname, Lastname, nationality, accountINT)
    );


